DEFAULT_ICONS = list(ICON_SVG.keys())


def _topic_to_query(topic: str) -> str:
    topic_lower = topic.lower()
    for key, val in UNSPLASH_TOPICS.items():
        if key in topic_lower:
            return val
    words = re.findall(r"[a-zA-Z]+", topic_lower)
    return ",".join(words[:3]) if words else UNSPLASH_TOPICS["default"]


def get_hero_image(topic: str) -> str:
    query = _topic_to_query(topic)
    seed = hashlib.md5(topic.encode()).hexdigest()[:8]
    return f"https://picsum.photos/seed/{seed}/1200/600"


def get_icon_svg(icon_name: str) -> str:
    key = icon_name.lower().strip()
    if key in ICON_SVG:
        return ICON_SVG[key]
    for k in ICON_SVG:
        if k in key or key in k:
            return ICON_SVG[k]
    idx = hash(key) % len(DEFAULT_ICONS)
    return ICON_SVG[DEFAULT_ICONS[idx]]


def get_testimonial_avatar(name: str) -> str:
    seed = hashlib.md5(name.encode()).hexdigest()[:8]
    return f"https://i.pravatar.cc/150?u={seed}"


def generate_image_urls(topic: str, sections: list) -> dict:
    images = {"hero": get_hero_image(topic)}
    for section in sections:
        if section.type.value == "hero" and not section.image_url:
            section.image_url = images["hero"]
    return images
